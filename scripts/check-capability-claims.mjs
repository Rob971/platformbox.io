#!/usr/bin/env node
/**
 * Website claim drift check.
 *
 * The marketing site must never claim a capability PlatformBox will not
 * deliver. This script fails the build when an explicitly annotated claim on
 * `src/lib/content.ts` rests on a capability that is:
 *
 *   - absent from the vendored projection (`src/lib/capability-claims.json`),
 *   - `websiteClaimAllowed: false`, or
 *   - `deliveryStatus` of `NOT_READY` / `NOT_OFFERED`, or
 *   - `referenceStatus` of `NOT_SUPPORTED` (the IDP itself says it is not built).
 *
 * How claims are identified is explicit, not guessed: every claim is a
 * `claims: ["pbx...."]` array written by hand on the content object that makes
 * the claim (see `day14.claims`, `offers[0].claims`, the sections of
 * `blueprint` / `technicalReference` / `technology`). The parser below matches
 * exactly that annotation pattern — a deliberate structure, never prose. A
 * claim that rests on no capability is marked explicitly with "__process__"
 * (a workflow/positioning statement) or "__pricing__", and skipped knowingly.
 *
 * The projection is generated by hand from `platformbox-capabilities.json` and
 * contains ONLY id/name/category/referenceStatus/deliveryStatus/packages/
 * websiteClaimAllowed — never `proven_with`, which holds engagement ids and is
 * therefore customer information.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const errors = [];
let claimCount = 0;

function assert(condition, message) {
  if (!condition) errors.push(message);
}

const claimsPath = path.join(root, "src/lib/capability-claims.json");
if (!fs.existsSync(claimsPath)) {
  console.error("check-capability-claims: src/lib/capability-claims.json not found.");
  console.error("  Generate it from platformbox-capabilities.json — never proven_with.");
  process.exit(1);
}
const claims = JSON.parse(fs.readFileSync(claimsPath, "utf8"));
assert(Array.isArray(claims), "capability-claims.json must be an array");
const byId = new Map(claims.map((c) => [c.id, c]));

// Extract the hand-authored `claims: [...]` annotation arrays (string literals
// only — never prose). The pattern matches exactly what we author in
// content.ts, so it is explicit by construction.
const contentPath = path.join(root, "src/lib/content.ts");
const content = fs.readFileSync(contentPath, "utf8");

const claimArrays = content.matchAll(/\bclaims:\s*\[([^\[\]]*)\]/g);
let annotationCount = 0;
for (const m of claimArrays) {
  annotationCount++;
  const ids = [...m[1].matchAll(/"([^"]+)"/g)].map((x) => x[1]);
  for (const id of ids) {
    claimCount++;
    if (id === "__process__" || id === "__pricing__") continue; // explicit non-capability marker
    const cap = byId.get(id);
    if (!cap) {
      console.error(`check-capability-claims: claimed capability "${id}" is not in capability-claims.json.`);
      assert(false, `"${id}" absent from the projection`);
      continue;
    }
    if (cap.websiteClaimAllowed === false) {
      console.error(
        `check-capability-claims: "${id}" (${cap.name}) — websiteClaimAllowed is false; the site must not claim it.`,
      );
      assert(false, `"${id}": websiteClaimAllowed false`);
    }
    if (cap.deliveryStatus === "NOT_READY" || cap.deliveryStatus === "NOT_OFFERED") {
      console.error(
        `check-capability-claims: "${id}" (${cap.name}) — deliveryStatus is ${cap.deliveryStatus}; the site must not claim it.`,
      );
      assert(false, `"${id}": deliveryStatus ${cap.deliveryStatus}`);
    }
    if (cap.referenceStatus === "NOT_SUPPORTED") {
      console.error(
        `check-capability-claims: "${id}" (${cap.name}) — referenceStatus is NOT_SUPPORTED; the IDP itself says it is not built.`,
      );
      assert(false, `"${id}": referenceStatus NOT_SUPPORTED`);
    }
  }
}

assert(annotationCount > 0, "no claims: [...] annotations found in content.ts — the check would be silent");
console.log(`Verified ${claimCount} claim(s) across ${annotationCount} annotation(s).`);

if (errors.length) {
  console.error("\nCapability claim enforcement failed:\n");
  for (const err of errors) console.error(`  ✖ ${err}`);
  console.error(`\n${errors.length} violation(s). Fix the claim in the copy or the projection, deliberately.\n`);
  process.exit(1);
}

console.log("Capability claim enforcement passed.");